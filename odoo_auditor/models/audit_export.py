import base64
import io

import xlsxwriter

from odoo import fields


def build_findings_xlsx(env, findings, run=None):
    """Return an xlsx attachment (ir.attachment) with a summary sheet and a findings sheet.

    Works on the records visible to the current user (record rules, incl. confidentiality, apply)."""
    buf = io.BytesIO()
    wb = xlsxwriter.Workbook(buf, {'in_memory': True, 'default_date_format': 'yyyy-mm-dd'})
    head = wb.add_format({'bold': True, 'bg_color': '#1f3a5f', 'font_color': '#ffffff', 'border': 1})
    bold = wb.add_format({'bold': True})
    money = wb.add_format({'num_format': '#,##0.00'})

    ws = wb.add_worksheet('Summary')
    ws.set_column(0, 0, 28)
    ws.set_column(1, 1, 40)
    rows = [('Generated', str(fields.Datetime.now())), ('Generated by', env.user.display_name),
            ('Findings in export', len(findings))]
    if run:
        rows = [('Audit run', run.name), ('Audit name', run.audit_name), ('Company', run.company_id.display_name),
                ('Period', '%s -> %s' % (run.date_from, run.date_to)), ('Status', run.state)] + rows
    for i, (k, v) in enumerate(rows):
        ws.write(i, 0, k, bold)
        ws.write(i, 1, v)
    base = len(rows) + 1
    ws.write(base, 0, 'Severity', head)
    ws.write(base, 1, 'Count', head)
    for j, sev in enumerate(('critical', 'high', 'medium', 'low', 'informational')):
        ws.write(base + 1 + j, 0, sev)
        ws.write(base + 1 + j, 1, len(findings.filtered(lambda f: f.severity == sev)))

    sheet = wb.add_worksheet('Findings')
    cols = ['Finding', 'Title', 'Rule', 'Domain', 'Severity', 'Status', 'Risk score', 'Estimated impact',
            'Source document', 'Source date', 'Partner', 'Assigned auditor', 'Process owner', 'Due date']
    widths = [16, 44, 10, 14, 12, 22, 10, 16, 24, 12, 26, 20, 20, 12]
    for c, (name, w) in enumerate(zip(cols, widths)):
        sheet.write(0, c, name, head)
        sheet.set_column(c, c, w)
    for r, f in enumerate(findings, start=1):
        values = [f.name, f.title, f.rule_code or '', f.domain_area or '', f.severity, f.state, f.risk_score,
                  f.estimated_impact, f.source_name or '', str(f.source_date or ''), f.partner_id.display_name or '',
                  f.assigned_user_id.display_name or '', f.process_owner_id.display_name or '', str(f.due_date or '')]
        for c, v in enumerate(values):
            sheet.write(r, c, v, money if c == 7 else None)
    sheet.freeze_panes(1, 2)
    sheet.autofilter(0, 0, max(len(findings), 1), len(cols) - 1)
    wb.close()

    name = ('%s.xlsx' % run.name.replace('/', '-')) if run else 'audit_findings.xlsx'
    return env['ir.attachment'].create({
        'name': name, 'type': 'binary', 'datas': base64.b64encode(buf.getvalue()),
        'mimetype': 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    })


def download_action(attachment):
    return {'type': 'ir.actions.act_url', 'url': '/web/content/%s?download=true' % attachment.id, 'target': 'self'}
